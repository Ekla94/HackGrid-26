from sqlalchemy import Boolean, Column, ForeignKey, Integer, String, Float, DateTime, Enum
from sqlalchemy.orm import relationship
import enum
import datetime
from database import Base

# --- ENUMS for predefined choices ---

class UserRole(enum.Enum):
    FPO = "fpo"       # Farmer Producer Organization (Seller)
    BUYER = "buyer"   # Supermarket, Cloud Kitchen, etc.
    DRIVER = "driver" # Logistics provider

class ContractStatus(enum.Enum):
    DRAFT = "draft"
    SIGNED = "signed"
    IN_TRANSIT = "in_transit"
    DELIVERED = "delivered"
    PAID = "paid"

# --- DATABASE MODELS ---

class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, index=True)
    role = Column(Enum(UserRole))
    phone = Column(String, unique=True, index=True)
    
    # Coordinates for Module 3: Google Maps Spatial Matchmaking
    location_lat = Column(Float, nullable=True) 
    location_lng = Column(Float, nullable=True)

    # Relationships: An FPO can have many crop batches listed
    crop_batches = relationship("CropBatch", back_populates="owner")


class CropBatch(Base):
    __tablename__ = "crop_batches"
    # Related to Module 1: BioTrace Crop Intelligence

    id = Column(Integer, primary_key=True, index=True)
    fpo_id = Column(Integer, ForeignKey("users.id"))
    
    crop_name = Column(String, index=True) # e.g., "Tomato", "Onion"
    quantity_kg = Column(Float)
    quality_grade = Column(String)         # e.g., "Grade A+" (From BioTrace mock)
    base_price_per_kg = Column(Float)
    is_certified = Column(Boolean, default=False)
    
    # Relationships
    owner = relationship("User", back_populates="crop_batches")
    contracts = relationship("Contract", back_populates="batch")


class MarketPrice(Base):
    __tablename__ = "market_prices"
    # Related to Module 2: KhetiNex Price-Arbitrage Engine

    id = Column(Integer, primary_key=True, index=True)
    crop_name = Column(String, index=True)
    market_city = Column(String, index=True) # e.g., "Mumbai", "Delhi"
    price_per_kg = Column(Float)
    updated_at = Column(DateTime, default=datetime.datetime.utcnow)


class Contract(Base):
    __tablename__ = "contracts"
    # Related to Module 4: GenAI Smart Contract & Escrow

    id = Column(Integer, primary_key=True, index=True)
    buyer_id = Column(Integer, ForeignKey("users.id"))
    seller_id = Column(Integer, ForeignKey("users.id"))
    batch_id = Column(Integer, ForeignKey("crop_batches.id"))
    
    total_amount = Column(Float)
    
    # The actual legal text generated by Gemini AI
    contract_text = Column(String) 
    
    status = Column(Enum(ContractStatus), default=ContractStatus.DRAFT)
    
    # Simulates the escrow geofenced payment trigger
    escrow_released = Column(Boolean, default=False) 
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    # Relationships
    batch = relationship("CropBatch", back_populates="contracts")

class BioChainVerification(Base):
    __tablename__ = 'biochain_verifications'
    id = Column(Integer, primary_key=True, index=True)
    farmer_id = Column(String, index=True)
    crop_name = Column(String)
    trust_score = Column(Integer)
    is_verified = Column(Boolean)
    field_score = Column(Float)
    ndvi_score = Column(Float)
    ai_score = Column(Float)
    sensor_score = Column(Float)
    trace_score = Column(Float)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)
